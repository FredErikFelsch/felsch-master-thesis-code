"""The init-data digest must be a function of the sources, not of the clock.

`policy.rego` is part of the init-data, and the init-data digest is measured into RTMR3 and
pinned as a reference value. If the generator wrote its own rendering timestamp into the
header of that file, two renderings from identical sources would produce two different
digests. Nothing would break while every deployment renders once and builds the services
image afterwards. The day it does not, the Authority pins the digest of an earlier rendering,
the controller sends a later one, and every run is refused with rtmr3-mismatch after a full
TD boot.

That refusal would be correct: a single changed comment line in the measured policy stops the
chain. What must not happen is that the line changes without anybody changing a source.
"""

from __future__ import annotations

import pathlib
import re
import unittest

from .profile_v5 import init_data_document, init_data_hash

MOCKS = pathlib.Path(__file__).resolve().parent.parent
GENPOLICY = MOCKS / "scripts" / "gke-v5" / "_genpolicy.sh"
INIT_DATA = MOCKS / "k8s" / "v5" / "init-data"

# Anything that renders a wall clock into a generated artefact. `date` is the usual culprit.
CLOCK = re.compile(r"\$\(date\b|%Y-%m-%d|strftime|time\.time\(\)")


class GeneratedPolicyCarriesNoClockTests(unittest.TestCase):
    """The rendered init-data carries no wall clock, so two renderings of one source agree."""

    def test_the_generator_writes_no_timestamp_into_the_policy_header(self):
        header_lines = [ln for ln in GENPOLICY.read_text().splitlines()
                        if "GENERATED by genpolicy" in ln and not ln.strip().startswith("#")]
        self.assertTrue(header_lines, "the header line moved, and this test has to follow it")
        for line in header_lines:
            self.assertIsNone(CLOCK.search(line),
                              f"a clock is back in the measured policy header: {line.strip()}")

    def test_the_rendered_policy_on_disk_carries_no_timestamp(self):
        policy = INIT_DATA / "policy.rego"
        head = policy.read_text()[:400]
        self.assertNotRegex(head, r"\bon 20\d\d-\d\d-\d\dT\d\d:\d\d:\d\dZ",
                            "the policy on disk was rendered by a generator that still stamps a time")

    def test_every_init_data_input_is_a_checked_in_file(self):
        """The three template files are inputs and must be in the tree, and the rendered document carries no timestamp."""
        document = init_data_document("eu.gcr.io/x/booking@sha256:" + "ab" * 32)
        self.assertNotRegex(document, r"\bon 20\d\d-\d\d-\d\dT\d\d:\d\d:\d\dZ")
        for name in ("aa.toml", "cdh.toml", "policy.rego"):
            self.assertTrue((INIT_DATA / name).exists(), f"{name} is an input and must be in the tree")

    def test_the_document_is_stable_across_two_renderings(self):
        """`init_data_document` reads no clock.

        This test guards the Python renderer, the header test above guards the shell generator.
        """
        image = "eu.gcr.io/x/booking@sha256:" + "cd" * 32
        first, second = init_data_document(image), init_data_document(image)
        self.assertEqual(init_data_hash(first), init_data_hash(second))


if __name__ == "__main__":
    unittest.main()
