"""A permissive kata-agent policy for probe pods that are not the runner.

On the V5 pod-VM overlay, `initdata-measure` measures the init-data digest into RTMR3 at
boot. A pod without init-data still becomes Ready, because the agents only pull the unit in
with Wants= (see scripts/gke-v5/18_probe_peer_pod.sh), but its measurement fails. Probes that
are not about policy enforcement, such as the network probes of
scripts/gke-v5/19_probe_network.sh, therefore still bring init-data along. Without it their
A5 and A5c verdicts (attacks of scripts/gke-v5/attack_catalogue.md) come back UNDECIDED
(scripts/gke-v5/README.md). That init-data needs a policy, and this module provides one
that allows every request.

The measured runner does not use it. It gets a policy generated by genpolicy for its own
manifest (`_genpolicy.sh`). The two cannot be confused where it matters: the init-data digest
goes into RTMR3, so a TD booted with this policy produces a different RTMR3 than a runner TD
and the Authority's reference pin refuses its evidence.

The request names are read from the pinned rules.rego of the Kata release in use instead of
being typed out here. A Kata version that adds a request would otherwise leave it undefined,
which the agent treats as a denial, and the probe would then fail for a reason that has
nothing to do with the network.
"""
from __future__ import annotations

import re
import sys

HEADER = """# GENERATED by booking_v5.permissive_policy from the pinned rules.rego.
# ALLOWS EVERYTHING. For probe pods that need a bootable init-data but are not about policy
# enforcement. The measured runner uses a genpolicy-generated policy instead.
package agent_policy
"""

_DEFAULT = re.compile(r"^default\s+([A-Za-z][A-Za-z0-9_]*)\s*:=\s*(?:true|false)\s*$", re.M)


def request_names(rules_rego: str) -> list[str]:
    """Return every rule the agent may ask about, in the order the pinned rules.rego lists them.

    Raises:
        ValueError: the file carries no `default ... :=` lines, so it is not a rules.rego.
    """
    names = list(dict.fromkeys(_DEFAULT.findall(rules_rego)))
    if not names:
        raise ValueError("no 'default <Rule> := true|false' lines found: not a kata rules.rego")
    return names


def permissive_policy(rules_rego: str) -> str:
    """Return a standalone agent policy that permits every request the rules.rego names.

    The policy holds only defaults and no rule bodies. It does not consult `policy_data`, so
    the document is valid on its own and no per-manifest generation step is needed.
    """
    lines = [f"default {name} := true" for name in request_names(rules_rego)]
    return HEADER + "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    """Print the permissive policy for the rules.rego named on the command line."""
    if len(argv) != 2:
        print(__doc__)
        print("usage: python3 -m booking_v5.permissive_policy <path to rules.rego>", file=sys.stderr)
        return 2
    with open(argv[1]) as fh:
        sys.stdout.write(permissive_policy(fh.read()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
